export const LANG_KEY = "guessmyorigin_lang";

export function getDict(code: LangCode): Dict {
  return DICTS[code] || en;
}

export function loadLang(): LangCode {
  if (typeof window === "undefined") return "fr";
  const saved = localStorage.getItem(LANG_KEY) as LangCode | null;
  if (saved && DICTS[saved]) return saved;
  return "fr";
}

export function modeLabels(t: Dict, mode: GameMode): { title: string; desc: string } {
  if (mode === "hardcore") {
    return { title: t.modeHardcore, desc: t.modeHardcoreDesc };
  }
  if (mode === "random") {
    return { title: t.modeRandom, desc: t.modeRandomDesc };
  }
  return { title: t.modeStandard, desc: t.modeStandardDesc };
}

